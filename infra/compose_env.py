"""Create the ignored env files for the local Docker Compose stack.

Writes `.env.compose` (application) and `.env.compose.db` (database/migrator) with
fresh random passwords, mode 0600. Reuses DEV_AUTH_TOKEN and FIREBASE_PROJECT_ID
from `.env.local` when present so one development token works everywhere.
Prints only file names, never values. Existing files are kept unless --force.
"""

from __future__ import annotations

import argparse
import os
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _read_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def _write(path: Path, values: dict[str, str]) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(
            "# Generated by infra/compose_env.py. Local development only; do not commit.\n"
        )
        for key, value in values.items():
            handle.write(f"{key}={value}\n")
    os.chmod(path, 0o600)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--force", action="store_true", help="Regenerate existing files"
    )
    args = parser.parse_args()
    app_file, db_file = ROOT / ".env.compose", ROOT / ".env.compose.db"
    if (app_file.exists() or db_file.exists()) and not args.force:
        print("compose env files already exist (use --force to regenerate)")
        return
    local = _read_env(ROOT / ".env.local")
    runtime_password = secrets.token_urlsafe(24)
    migrator_password = secrets.token_urlsafe(24)
    runtime_url = (
        f"postgresql+psycopg://agentping_runtime:{runtime_password}@db:5432/agentping"
    )
    _write(
        app_file,
        {
            "APP_ENV": "development",
            "AUTH_MODE": "development",
            "DEV_AUTH_TOKEN": local.get("DEV_AUTH_TOKEN") or secrets.token_urlsafe(32),
            "DATABASE_URL": runtime_url,
            "WORKER_LISTEN_DATABASE_URL": runtime_url,
            "PUBLIC_BASE_URL": "http://127.0.0.1:8000",
            "PUSH_PROVIDER": "log",
            "FIREBASE_PROJECT_ID": local.get("FIREBASE_PROJECT_ID", ""),
            "GOOGLE_CLOUD_PROJECT": local.get("GOOGLE_CLOUD_PROJECT", ""),
            "WORKER_TRIGGER_TOKEN": secrets.token_urlsafe(32),
            "LOG_JSON": "true",
        },
    )
    _write(
        db_file,
        {
            "POSTGRES_PASSWORD": migrator_password,
            "RUNTIME_DB_PASSWORD": runtime_password,
            "MIGRATION_DATABASE_URL": (
                f"postgresql+psycopg://agentping_migrator:{migrator_password}@db:5432/agentping"
            ),
        },
    )
    print(f"wrote {app_file.name} and {db_file.name} (mode 0600)")


if __name__ == "__main__":
    main()
